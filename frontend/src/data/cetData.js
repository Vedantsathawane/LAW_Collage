export const isRecordPublished = (record) => {
  if (!record || !record.date) return true;
  try {
    const pubTime = record.publicationTime || "13:00";
    const isoString = `${record.date}T${pubTime}:00+05:30`;
    const targetDate = new Date(isoString);
    const now = new Date();
    return now >= targetDate;
  } catch (e) {
    return true;
  }
};

export const getSortedCETResults = () => {
  return CET_YEAR_DATA.map((yearGroup) => {
    const sortedRecords = [...yearGroup.records].sort((a, b) => {
      return new Date(b.date).getTime() - new Date(a.date).getTime();
    });
    return {
      ...yearGroup,
      records: sortedRecords
    };
  }).sort((a, b) => b.yearNum - a.yearNum);
};

